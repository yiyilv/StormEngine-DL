MODEL_NAMES = (
    "v7_b",
    "v8_stage2_seed42",
    "v8_stage2_seed43",
    "v8_stage3a_seed42",
    "v8_stage3a_seed43",
)
BASELINE_NAMES = ("sparse_reconstruction_persistence", "dense_era5_persistence")
ALL_PREDICTIONS = MODEL_NAMES + BASELINE_NAMES
TARGETS = ("msl", "u10", "v10", "t2m", "tp")


def read_yaml(path: Path) -> dict[str, Any]:
    value = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError(f"Expected a mapping in {path}")
    return value


def write_json(path: Path, value: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes((json.dumps(value, indent=2) + "\n").encode("utf-8"))


def publish_result(source: Path, destination: Path, result: dict[str, Any]) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    benchmark_path = destination / "benchmark.json"
    benchmark_path.write_bytes(source.read_bytes())
    acceptance = result["acceptance"]
    rows = acceptance["seed_results"]
    lines = [
        "# V8 frozen 2016 validation benchmark",
        "",
        "All models use the same clean 2016 windows; event thresholds use only "
        "2010--2015, and the V8 2017 test split is not read.",
        "",
        f"- Both Stage-3A seeds passed: `{acceptance['both_seeds_passed']}`",
        f"- Samples: `{result['contract']['samples']}`",
        f"- Window stride: `{result['contract']['window_stride_hours']} h`",
        "",
        "| seed | mean sea skill vs Stage 2 | fair-persistence u10 leads | fair-persistence v10 leads | reconstruction gate | passed |",
        "|---:|---:|---:|---:|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row['seed']} | {100 * row['mean_sea_rmse_skill_vs_stage2']:.2f}% "
            f"| {row['positive_sea_wind_leads_vs_fair_persistence']['u10']}/6 "
            f"| {row['positive_sea_wind_leads_vs_fair_persistence']['v10']}/6 "
            f"| {row['reconstruction_gate_passed']} | {row['passed']} |"
        )
    lines.extend(
        [
            "",
            "`benchmark.json` contains full/land/sea MAE and RMSE, +1--+6 h "
            "metrics, RMSE skill, and wind/precipitation/low-pressure event verification.",
            "",
        ]
    )
    readme_path = destination / "README.md"
    readme_path.write_bytes(("\n".join(lines)).encode("utf-8"))
    files = []
    for path in (benchmark_path, readme_path):
        files.append(
            {
                "path": path.name,
                "bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
        )
    write_json(
        destination / "manifest.json",
        {
            "schema_version": 1,
            "hash_scope": "Git-ready LF bytes generated by the benchmark evaluator",
            "test_years_read": [],
            "files": files,
        },
    )


def checkpoint_path_and_hash(spec: dict[str, Any]) -> tuple[Path, str]:
    path = resolve(spec["path"])
    if not path.is_file():
        raise FileNotFoundError(f"Missing frozen checkpoint: {path}")
    actual = sha256_file(path)
    expected = str(spec["sha256"])
    if actual != expected:
        raise ValueError(f"Checkpoint SHA-256 mismatch for {path}: {actual}")
    return path, actual


def load_models(
    benchmark: dict[str, Any],
    device: torch.device,
    station_count: int,
    model_names: tuple[str, ...] = MODEL_NAMES,
) -> tuple[dict[str, torch.nn.Module], dict[str, dict[str, Any]]]:
    stage3_base = load_config(resolve(benchmark["data_config"]))
    models: dict[str, torch.nn.Module] = {}
    metadata: dict[str, dict[str, Any]] = {}
    for name in model_names:
        spec = dict(benchmark["checkpoints"][name])
        path, digest = checkpoint_path_and_hash(spec)
        saved = torch.load(path, map_location=device, weights_only=False)
        if name == "v7_b":
            config = load_config(resolve(benchmark["v7_b_config"]))
            model = make_model(config).to(device)
            require_v7_checkpoint_contract(saved, v7_contract(config, model, station_count))
        else:
            config = json.loads(json.dumps(stage3_base))
            config["seed"] = int(spec["seed"])
            model = make_model(config).to(device)
            phase = "stage3a" if spec["phase"] == "stage2" else "stage3b"
            validate_source_checkpoint(saved, phase, config)
        model.load_state_dict(saved["model_state_dict"], strict=True)
        model.eval()
        models[name] = model
        metadata[name] = {
            "path": str(path),
            "sha256": digest,
            "checkpoint_contract": saved.get("model_contract"),
        }
    return models, metadata


def _physical_channel(
    values: np.ndarray, variable: str, normalization: NormalizationStats
) -> np.ndarray:
    stat = normalization.variables[variable]
    return values.astype(np.float32, copy=False) * np.float32(stat.std) + np.float32(stat.mean)


def derive_event_thresholds(
    dataset: Any,
    variables: list[str],
    normalization: NormalizationStats,
    land_mask: np.ndarray,
    years: list[int],
    event_config: dict[str, Any],
) -> dict[str, Any]:
    """Derive fixed thresholds only from the declared training years."""
    all_years = dataset.all_times.astype("datetime64[Y]").astype(np.int64) + 1970
    indices = np.flatnonzero(np.isin(all_years, np.asarray(years, dtype=np.int64)))
    if indices.size == 0:
        raise ValueError("No cache hours found for threshold years")
    if int(all_years[indices].min()) != min(years) or int(all_years[indices].max()) != max(years):
        raise ValueError("Threshold cache does not cover the declared boundary years")
    sea = np.asarray(land_mask) < 0.5

    def read(name: str) -> np.ndarray:
        channel = variables.index(name)
        chunks = []
        for start in range(0, len(indices), 744):
            selected = indices[start : start + 744]
            normalized = np.asarray(dataset.target_grids[selected, channel], dtype=np.float32)
            chunks.append(_physical_channel(normalized[:, sea], name, normalization).reshape(-1))
        return np.concatenate(chunks)

    u10 = read("u10")
    v10 = read("v10")
    wind = np.sqrt(np.square(u10) + np.square(v10))
    wind_threshold = float(np.quantile(wind, float(event_config["strong_wind_quantile"])))
    del u10, v10, wind

    tp = read("tp")
    wet_minimum = float(event_config["wet_precipitation_minimum_mm"])
    wet = tp[tp >= wet_minimum]
    if wet.size == 0:
        raise ValueError("Training data contain no wet precipitation cells")
    wet_tp_threshold = float(np.quantile(wet, float(event_config["wet_precipitation_quantile"])))
    wet_fraction = float(wet.size / tp.size)
    del wet, tp

    msl = read("msl")
    low_msl_threshold = float(np.quantile(msl, float(event_config["low_msl_quantile"])))
    del msl
    return {
        "source_years": years,
        "region": "sea (land-sea mask < 0.5)",
        "strong_wind_q95_ms": wind_threshold,
        "heavy_precipitation_wet_q95_mm": wet_tp_threshold,
        "heavy_precipitation_fixed_mm": float(event_config["fixed_precipitation_threshold_mm"]),
        "low_msl_q05_hpa": low_msl_threshold,
        "wet_precipitation_minimum_mm": wet_minimum,
        "wet_cell_fraction": wet_fraction,
        "definitions": {
            "strong_wind_q95_ms": "95th percentile of training-period sea-cell sqrt(u10^2+v10^2)",
            "heavy_precipitation_wet_q95_mm": "95th percentile among training sea cells with tp >= wet minimum",
            "heavy_precipitation_fixed_mm": "fixed preceding-hour precipitation threshold",
            "low_msl_q05_hpa": "5th percentile of training-period sea-cell mean sea-level pressure",
        },
    }


def make_event_accumulators(
    forecast_hours: int, thresholds: dict[str, Any]
) -> dict[str, EventMetricAccumulator]:
    return {
        "strong_wind_q95": EventMetricAccumulator(
            forecast_hours, direction="above", threshold=thresholds["strong_wind_q95_ms"]
        ),
        "heavy_precipitation_wet_q95": EventMetricAccumulator(
            forecast_hours,
            direction="above",
            threshold=thresholds["heavy_precipitation_wet_q95_mm"],
        ),
        "heavy_precipitation_fixed_5mm": EventMetricAccumulator(
            forecast_hours,
            direction="above",
            threshold=thresholds["heavy_precipitation_fixed_mm"],
        ),
        "low_msl_q05": EventMetricAccumulator(
            forecast_hours, direction="below", threshold=thresholds["low_msl_q05_hpa"]
        ),
    }


def update_events(
    accumulators: dict[str, EventMetricAccumulator],
    prediction: torch.Tensor,
    target: torch.Tensor,
    sea_mask: torch.Tensor,
    variables: list[str],
) -> None:
    u, v = variables.index("u10"), variables.index("v10")
    wind_prediction = torch.sqrt(prediction[:, :, u].square() + prediction[:, :, v].square())
    wind_target = torch.sqrt(target[:, :, u].square() + target[:, :, v].square())
    accumulators["strong_wind_q95"].update(wind_prediction, wind_target, sea_mask)
    tp = variables.index("tp")
    for name in ("heavy_precipitation_wet_q95", "heavy_precipitation_fixed_5mm"):
        accumulators[name].update(prediction[:, :, tp], target[:, :, tp], sea_mask)
    msl = variables.index("msl")
    accumulators["low_msl_q05"].update(prediction[:, :, msl], target[:, :, msl], sea_mask)


def skill(candidate: dict[str, Any], baseline: dict[str, Any]) -> dict[str, Any]:
    def compare(candidate_regions: dict[str, Any], baseline_regions: dict[str, Any]) -> dict[str, Any]:
        result = {}
        for region in ("full", "land", "sea"):
            result[region] = {}
            for variable in TARGETS:
                candidate_rmse = float(candidate_regions[region][variable]["rmse"])
                baseline_rmse = float(baseline_regions[region][variable]["rmse"])
                result[region][variable] = {
                    "candidate_rmse": candidate_rmse,
                    "baseline_rmse": baseline_rmse,
                    "skill": None if baseline_rmse == 0 else 1.0 - candidate_rmse / baseline_rmse,
                }
        return result

    return {
        "definition": "1 - candidate_RMSE / baseline_RMSE; positive means candidate is better",
        "aggregate": compare(candidate["aggregate"], baseline["aggregate"]),
        "by_lead_hour": {
            lead: compare(regions, baseline["by_lead_hour"][lead])
            for lead, regions in candidate["by_lead_hour"].items()
        },
    }


def acceptance_result(
    metrics: dict[str, Any],
    skills: dict[str, Any],
    benchmark: dict[str, Any],
) -> dict[str, Any]:
    minimum_leads = int(benchmark["acceptance"]["minimum_positive_wind_leads_per_component"])
    seed_rows = []
    for seed in (42, 43):
        stage3 = f"v8_stage3a_seed{seed}"
        stage2 = f"v8_stage2_seed{seed}"
        stage2_skill = skills[f"{stage3}_vs_{stage2}"]
        fair_skill = skills[f"{stage3}_vs_sparse_reconstruction_persistence"]
        sea_skills = [stage2_skill["aggregate"]["sea"][name]["skill"] for name in TARGETS]
        wind_counts = {
            variable: sum(
                fair_skill["by_lead_hour"][str(lead)]["sea"][variable]["skill"] > 0
                for lead in range(1, 7)
            )
            for variable in ("u10", "v10")
        }
        lead_growth = {
            variable: (
                metrics[stage3]["by_lead_hour"]["6"]["sea"][variable]["rmse"]
                >= metrics[stage3]["by_lead_hour"]["1"]["sea"][variable]["rmse"]
            )
            for variable in ("u10", "v10")
        }
        summary_path = resolve(benchmark["checkpoints"][stage3]["summary"])
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        reconstruction_passed = bool(summary["reconstruction"]["preservation_gate_passed"])
        row = {
            "seed": seed,
            "mean_sea_rmse_skill_vs_stage2": float(sum(sea_skills) / len(sea_skills)),
            "sea_rmse_skill_vs_stage2_by_variable": dict(zip(TARGETS, sea_skills)),
            "positive_sea_wind_leads_vs_fair_persistence": wind_counts,
            "sea_wind_rmse_lead6_not_better_than_lead1": lead_growth,
            "reconstruction_gate_passed": reconstruction_passed,
        }
        row["passed"] = bool(
            row["mean_sea_rmse_skill_vs_stage2"] > 0
            and all(count >= minimum_leads for count in wind_counts.values())
            and all(lead_growth.values())
            and reconstruction_passed
        )
        seed_rows.append(row)
    return {
        "preregistered_on": "2016 validation before reading the locked 2017 V8 test split",
        "minimum_positive_wind_leads_per_component": minimum_leads,
        "seed_results": seed_rows,
        "both_seeds_passed": all(row["passed"] for row in seed_rows),
        "interpretation": (
            "Event metrics are reported diagnostics and are not threshold-tuned pass gates. "
            "Failure keeps 2017 locked; passing permits model freezing before the one-time test."
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/v8_2016_benchmark.yaml")
    parser.add_argument("--mode", choices=("preflight", "evaluate"), default="preflight")
    parser.add_argument("--device", choices=("auto", "cuda", "cpu"), default="auto")
    parser.add_argument("--max-batches", type=int)
    parser.add_argument("--output-dir")
    parser.add_argument("--publish-dir")
    args = parser.parse_args()

    benchmark = read_yaml(resolve(args.config))
    stage3_config = load_config(resolve(benchmark["data_config"]))
    validation_years = list(benchmark["validation_years"])
    if validation_years != [2016]:
        raise ValueError("The frozen benchmark validation split must be exactly [2016]")
    if list(stage3_config["data"]["test_years"]) != [2017]:
        raise ValueError("The locked V8 test-year declaration unexpectedly changed")
    stage3_config["data"]["window_stride_hours"] = int(benchmark["window_stride_hours"])
    dataset = make_dataset(stage3_config, validation_years, augment=False)
    if len(dataset.station_ids) != 390:
        raise ValueError("Benchmark requires the fixed 390-station profile")
    variables = list(stage3_config["data"]["target_variables"])
    if variables != list(TARGETS):
        raise ValueError(f"Benchmark target order must be {TARGETS}")
    device = torch.device(
        "cuda" if args.device == "auto" and torch.cuda.is_available()
        else "cpu" if args.device == "auto" else args.device
    )
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA requested but unavailable")
    models, checkpoint_metadata = load_models(benchmark, device, len(dataset.station_ids))
    static_data = StaticFields.load(resolve(stage3_config["data"]["static_fields"]))
    static = static_data.as_tensor().unsqueeze(0).to(device)
    land_mask = torch.from_numpy(static_data.land_sea_mask)
    sea_mask = land_mask < 0.5
    normalization = NormalizationStats.load(resolve("data/normalization/era5_2010_2015.json"))
    forecast_hours = int(stage3_config["data"]["forecast_hours"])
    history_hours = int(stage3_config["data"]["history_hours"])
    loader = DataLoader(
        dataset,
        batch_size=int(benchmark["evaluation"]["batch_size"]),
        shuffle=False,
        num_workers=0,
        pin_memory=device.type == "cuda",
    )
    first_raw = next(iter(loader))
    first = move(first_raw, device)
    with torch.no_grad():
        shapes = {name: list(forward(model, first, static).shape) for name, model in models.items()}
    preflight = {
        "schema_version": 1,
        "mode": "preflight",
        "device": str(device),
        "validation_years": validation_years,
        "threshold_years": list(benchmark["threshold_years"]),
        "test_years_read": [],
        "samples": len(dataset),
        "batches": len(loader),
        "window_stride_hours": int(benchmark["window_stride_hours"]),
        "station_count": len(dataset.station_ids),
        "variables": variables,
        "model_output_shapes": shapes,
        "checkpoint_metadata": checkpoint_metadata,
    }
    output = resolve(args.output_dir or benchmark["evaluation"]["output_dir"])
    write_json(output / "preflight.json", preflight)
    print(
        f"Preflight OK: samples={len(dataset):,} batches={len(loader):,} "
        f"models={len(models)} test_years_read=[]",
        flush=True,
    )
    if args.mode == "preflight":
        dataset.close()
        return 0

    thresholds = derive_event_thresholds(
        dataset,
        variables,
        normalization,
        static_data.land_sea_mask,
        list(benchmark["threshold_years"]),
        benchmark["events"],
    )
    metric_accumulators = {
        name: ForecastMetricAccumulator(tuple(variables), forecast_hours)
        for name in ALL_PREDICTIONS
    }
    event_accumulators = {
        name: make_event_accumulators(forecast_hours, thresholds)
        for name in ALL_PREDICTIONS
    }
    processed = 0
    started = time.perf_counter()
    expected_batches = min(len(loader), args.max_batches) if args.max_batches else len(loader)
    sparse_model = models[str(benchmark["baselines"]["sparse_reconstruction_checkpoint"])]
    with torch.no_grad():
        for batch_index, raw in enumerate(loader):
            if args.max_batches is not None and batch_index >= args.max_batches:
                break
            batch = move(raw, device)
            target = denormalize_channels(batch["target"], variables, normalization)
            predictions: dict[str, torch.Tensor] = {
                name: denormalize_channels(forward(model, batch, static), variables, normalization)
                for name, model in models.items()
            }

            current_batch = {
                "point_values": batch["point_values"][:, -1:],
                "value_mask": batch["value_mask"][:, -1:],
                "observation_age": batch["observation_age"][:, -1:],
                "point_coords": batch["point_coords"],
                "point_static": batch["point_static"],
                "target": batch["target"][:, :1],
            }
            reconstructed = reconstruction_forward(sparse_model, current_batch, static)[:, 0]
            reconstructed = denormalize_channels(
                reconstructed[:, None], variables, normalization
            )[:, 0]
            predictions["sparse_reconstruction_persistence"] = dense_grid_persistence(
                reconstructed, forecast_hours
            )

            current_indices = raw["start_index"].numpy() + history_hours - 1
            current_normalized = torch.from_numpy(
                np.asarray(dataset.target_grids[current_indices], dtype=np.float32).copy()
            ).to(device)
            current_dense = denormalize_channels(
                current_normalized[:, None], variables, normalization
            )[:, 0]
            predictions["dense_era5_persistence"] = dense_grid_persistence(
                current_dense, forecast_hours
            )

            for name, prediction in predictions.items():
                metric_accumulators[name].update(prediction, target, land_mask)
                update_events(event_accumulators[name], prediction, target, sea_mask, variables)
            processed += int(target.shape[0])
            completed = batch_index + 1
            progress_every = int(benchmark["evaluation"]["progress_every_batches"])
            if progress_every > 0 and (completed % progress_every == 0 or completed == expected_batches):
                elapsed = time.perf_counter() - started
                eta = elapsed / completed * max(0, expected_batches - completed)
                print(
                    f"  2016 benchmark {completed:,}/{expected_batches:,} "
                    f"elapsed={elapsed / 60:.1f}m ETA={eta / 60:.1f}m",
                    flush=True,
                )

    metrics = {name: accumulator.compute() for name, accumulator in metric_accumulators.items()}
    event_metrics = {
        name: {event: accumulator.compute() for event, accumulator in values.items()}
        for name, values in event_accumulators.items()
    }
    skills: dict[str, Any] = {}
    for seed in (42, 43):
        stage3 = f"v8_stage3a_seed{seed}"
        stage2 = f"v8_stage2_seed{seed}"
        for baseline in (stage2, *BASELINE_NAMES, "v7_b"):
            skills[f"{stage3}_vs_{baseline}"] = skill(metrics[stage3], metrics[baseline])
    acceptance = acceptance_result(metrics, skills, benchmark)
    bounded = args.max_batches is not None and args.max_batches < len(loader)
    result = {
        "schema_version": 1,
        "scientific_status": "bounded_pipeline_check" if bounded else "frozen_2016_validation_benchmark",
        "contract": {
            "validation_years": validation_years,
            "threshold_years": list(benchmark["threshold_years"]),
            "test_years_read": [],
            "window_stride_hours": int(benchmark["window_stride_hours"]),
            "history_hours": history_hours,
            "forecast_hours": forecast_hours,
            "station_count": len(dataset.station_ids),
            "target_variables": variables,
            "samples": processed,
            "batches": expected_batches,
            "baseline_definitions": benchmark["baselines"],
        },
        "checkpoint_metadata": checkpoint_metadata,
        "event_thresholds": thresholds,
        "metrics": metrics,
        "rmse_skills": skills,
        "event_metrics": event_metrics,
        "acceptance": acceptance,
        "elapsed_seconds": time.perf_counter() - started,
    }
    write_json(output / "benchmark.json", result)
    if args.publish_dir:
        if bounded:
            raise ValueError("A bounded benchmark cannot be published as a scientific result")
        publish_result(
            output / "benchmark.json", resolve(args.publish_dir), result
        )
    print(
        f"Benchmark complete: status={result['scientific_status']} "
        f"both_seeds_passed={acceptance['both_seeds_passed']} output={output / 'benchmark.json'}"
        + (f" published={resolve(args.publish_dir)}" if args.publish_dir else ""),
        flush=True,
    )
    dataset.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
